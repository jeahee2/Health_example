import pandas as pd

# ==========================================
# 1. 엑셀 파일
# ==========================================

file_path = "성분사용실적_세로형.xlsx"


# ==========================================
# 2. 엑셀 읽기
# ==========================================

df = pd.read_excel(file_path)

print("원본 데이터")
print(df.head())

print("\n원본 컬럼")
print(df.columns.tolist())


# ==========================================
# 3. 필요한 컬럼만 선택
#    요양기관종별, 시군구명칭 제거
# ==========================================

result = df[
    [
        "성분코드",
        "성분명",
        "시도명칭",
        "기간",
        "수량",
        "금액"
    ]
].copy()


# ==========================================
# 4. 컬럼 이름 변경
# ==========================================

result = result.rename(
    columns={
        "시도명칭": "시도",
        "기간": "진료년월"
    }
)


# ==========================================
# 5. 수량 / 금액 숫자로 변환
# ==========================================

result["수량"] = pd.to_numeric(
    result["수량"],
    errors="coerce"
).fillna(0)


result["금액"] = pd.to_numeric(
    result["금액"],
    errors="coerce"
).fillna(0)


# ==========================================
# 6. 요양기관종별 데이터 합산
#
# 같은
# 성분코드 + 성분명 + 시도 + 진료년월
# 을 하나로 합침
# ==========================================

result = (
    result
    .groupby(
        [
            "성분코드",
            "성분명",
            "시도",
            "진료년월"
        ],
        as_index=False
    )
    .agg(
        {
            "수량": "sum",
            "금액": "sum"
        }
    )
)


# ==========================================
# 7. 정렬
# ==========================================

result = result.sort_values(
    by=[
        "성분코드",
        "시도",
        "진료년월"
    ]
)


# ==========================================
# 8. 결과 확인
# ==========================================

print("\n==========================================")
print("요양기관종별 합산 결과")
print("==========================================")

print(result.head(20))


print("\n최종 컬럼")

print(
    result.columns.tolist()
)


print("\n최종 데이터 개수")

print(
    len(result)
)


# ==========================================
# 9. CSV 저장
# ==========================================

result.to_csv(
    "health_data.csv",
    index=False,
    encoding="utf-8-sig"
)


print("\n==========================================")
print("저장 완료!")
print("==========================================")

print(
    "health_data.csv"
)