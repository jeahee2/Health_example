import pandas as pd

# ==========================================
# 1. 엑셀 파일
# ==========================================

file_path = "아나스트로졸_강원_정리본.xlsx"


# ==========================================
# 2. 엑셀 읽기
# ==========================================

df = pd.read_excel(file_path)

print("원본 데이터")
print(df.head())

print("\n원본 컬럼")
print(df.columns.tolist())


# ==========================================
# 3. 필요한 컬럼만 선택
#    (시군구는 유지, 요양기관종별은 원본에 없음)
#    수량 / 금액 값은 원본 그대로 사용 (가공/합산 없음)
# ==========================================

result = df[
    [
        "성분코드",
        "성분명",
        "시도",
        "시군구",
        "진료년월",
        "수량",
        "금액"
    ]
].copy()


# ==========================================
# 3-1. 연도 컬럼 추가
#      진료년월 (예: 2025-01) 앞 4자리를 연도로 사용
# ==========================================

result["연도"] = (
    result["진료년월"]
    .astype(str)
    .str[:4]
)

result = result[
    [
        "성분코드",
        "성분명",
        "시도",
        "시군구",
        "연도",
        "진료년월",
        "수량",
        "금액"
    ]
]


# ==========================================
# 4. 정렬
#    (값 자체는 건드리지 않고 보기 좋게 정렬만)
# ==========================================

result = result.sort_values(
    by=[
        "성분코드",
        "시도",
        "시군구",
        "진료년월"
    ]
)


# ==========================================
# 5. 결과 확인
# ==========================================

print("\n==========================================")
print("정리 결과 (원본 데이터 그대로, 컬럼만 선택/정렬)")
print("==========================================")

print(result.head(20))


print("\n최종 컬럼")

print(
    result.columns.tolist()
)


print("\n최종 데이터 개수")

print(
    len(result)
)


# ==========================================
# 6. CSV 저장
# ==========================================

result.to_csv(
    "health_data.csv",
    index=False,
    encoding="utf-8-sig"
)


print("\n==========================================")
print("저장 완료!")
print("==========================================")

print(
    "health_data.csv"
)